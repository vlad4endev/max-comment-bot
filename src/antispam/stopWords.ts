export interface StopWordIndex {
  exact: Map<string, number>
  partial: Array<[string, number]>
}

export function buildStopWordIndexes(
  dict: Record<number, string[]>,
  extraExact?: Map<string, number>,
): StopWordIndex {
  const exact = new Map<string, number>(extraExact)
  const partial: Array<[string, number]> = []
  for (const [score, words] of Object.entries(dict)) {
    const weight = Number(score)
    for (const raw of words) {
      const w = String(raw).toLowerCase().trim()
      if (!w) {
        continue
      }
      if (w.includes(' ')) {
        partial.push([w, weight])
      } else {
        exact.set(w, weight)
      }
    }
  }
  return { exact, partial }
}

export function checkStopWords(tokens: string[], index: StopWordIndex): number {
  let total = 0
  const found = new Set<string>()
  for (const t of tokens) {
    if (index.exact.has(t)) {
      const w = index.exact.get(t)!
      const tag = `exact:${t}`
      if (!found.has(tag)) {
        found.add(tag)
        total += w
      }
    }
  }
  for (let i = 0; i < tokens.length - 1; i++) {
    const bg = `${tokens[i]} ${tokens[i + 1]}`
    for (const [sw, w] of index.partial) {
      if (bg.includes(sw) && !found.has(sw)) {
        found.add(sw)
        total += w
      }
    }
  }
  return total
}
